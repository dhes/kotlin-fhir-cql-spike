"""Generate the element table that maps kotlin-fhir R4 classes to CQL FHIR model types.

Usage: python3 -I tools/generate_elements.py <fhir-modelinfo-4.0.1.xml> <kotlin-fhir r4 model source dir> <output .kt>

For every type in the FHIR model info that has a kotlin-fhir class of the same name, this writes
a function that lists the type's elements (its own and inherited ones) in model-info order, each
with its declared model-info type and the kotlin-fhir property that holds it, and a dispatcher
that picks the function by the runtime class of a value.
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = {"m": "urn:hl7-org:elm-modelinfo:r1", "xsi": "http://www.w3.org/2001/XMLSchema-instance"}
XSI_TYPE = "{http://www.w3.org/2001/XMLSchema-instance}type"
KOTLIN_PACKAGE = "dev.ohs.fhir.model.r4"


def kotlin_classes(source_dir: Path) -> set[str]:
    """Return the qualified names (e.g. "Immunization.Performer") of classes in the model package."""
    names: set[str] = set()
    decl = re.compile(r"^( *)public (?:(?:open|abstract|data|sealed) )*class (\w+)\b")
    for path in sorted(source_dir.glob("*.kt")):
        stack: list[tuple[int, str]] = []
        for line in path.read_text().splitlines():
            m = decl.match(line)
            if not m:
                continue
            indent = len(m.group(1))
            while stack and stack[-1][0] >= indent:
                stack.pop()
            stack.append((indent, m.group(2)))
            names.add(".".join(n for _, n in stack))
    return names


def kotlin_name(model_name: str) -> str:
    """Model-info type name to kotlin-fhir class name: capitalize each dotted part."""
    return ".".join(p[:1].upper() + p[1:] for p in model_name.split("."))


def element_type(element) -> tuple[str | None, bool]:
    """Return (declared type, is list). A choice has declared type None."""
    if element.get("elementType"):
        return element.get("elementType"), False
    spec = element.find("m:elementTypeSpecifier", NS)
    if spec is None:
        return None, False
    kind = spec.get(XSI_TYPE)
    if kind == "ListTypeSpecifier":
        if spec.get("elementType"):
            return spec.get("elementType"), True
        inner = spec.find("m:elementTypeSpecifier", NS)
        if inner is not None and inner.get(XSI_TYPE) == "NamedTypeSpecifier":
            return f'{inner.get("namespace")}.{inner.get("name")}', True
        return None, True
    if kind == "NamedTypeSpecifier":
        return f'{spec.get("namespace")}.{spec.get("name")}', False
    return None, False  # ChoiceTypeSpecifier


def main() -> None:
    modelinfo, source_dir, output = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    root = ET.parse(modelinfo).getroot()
    types = {t.get("name"): t for t in root.findall("m:typeInfo", NS) if t.get("namespace") == "FHIR"}
    classes = kotlin_classes(source_dir)

    def base(name: str) -> str | None:
        b = types[name].get("baseType") or ""
        return b[len("FHIR."):] if b.startswith("FHIR.") else None

    def depth(name: str) -> int:
        d, b = 0, base(name)
        while b is not None:
            d, b = d + 1, base(b)
        return d

    def elements(name: str) -> list:
        b = base(name)
        inherited = elements(b) if b is not None and b in types else []
        own = types[name].findall("m:element", NS)
        own_names = {e.get("name") for e in own}
        return [e for e in inherited if e.get("name") not in own_names] + own

    generated = sorted(
        (n for n in types if kotlin_name(n) in classes),
        key=lambda n: (-depth(n), n),
    )
    skipped = sorted(n for n in types if kotlin_name(n) not in classes)

    out = []
    out.append("// GENERATED by tools/generate_elements.py from fhir-modelinfo-4.0.1.xml (cqframework quick")
    out.append("// 5.4.0) and the class list of kotlin-fhir fhir-model-r4 1.0.0-rc04. Do not edit by hand.")
    out.append("@file:Suppress(\"LargeClass\", \"LongMethod\", \"CyclomaticComplexMethod\")")
    out.append("")
    out.append("package io.github.dhes.kotlinfhircql.generated")
    out.append("")
    out.append("import io.github.dhes.kotlinfhircql.Slot")
    out.append("import io.github.dhes.kotlinfhircql.Structure")
    out.append("")
    out.append(f"// {len(generated)} model-info types have a kotlin-fhir class; {len(skipped)} do not")
    out.append("// (value-set types, profiles and others), and their values are typed by the element that holds them.")
    out.append("")
    out.append("internal fun structureOf(v: Any): Structure? =")
    out.append("  when (v) {")
    for n in generated:
        out.append(f"    is {KOTLIN_PACKAGE}.{kotlin_name(n)} -> {fun_name(n)}(v)")
    out.append("    else -> null")
    out.append("  }")
    for n in generated:
        out.append("")
        out.append(f"private fun {fun_name(n)}(v: {KOTLIN_PACKAGE}.{kotlin_name(n)}) =")
        out.append(f'  Structure("{n}", listOf(')
        for e in elements(n):
            declared, is_list = element_type(e)
            d = f'"{declared}"' if declared else "null"
            out.append(f'    Slot("{e.get("name")}", {d}, v.`{e.get("name")}`),')
        out.append("  ))")
    output.write_text("\n".join(out) + "\n")
    print(f"generated {len(generated)} types, skipped {len(skipped)}", file=sys.stderr)


def fun_name(model_name: str) -> str:
    return "s" + "_".join(model_name.split("."))


if __name__ == "__main__":
    main()
